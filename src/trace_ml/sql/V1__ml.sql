-- ml 스키마 표 3개. GAKDO/docs db/V1__init.sql의 ml 절 그대로이고, 다시 실행해도 되게 IF NOT EXISTS만 더했다.
-- 스키마 자체는 gitops base/postgres/init-db.sh가 만든다.
CREATE SCHEMA IF NOT EXISTS ml;

CREATE TABLE IF NOT EXISTS ml.dataset_device (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_code  varchar(8)  NOT NULL UNIQUE,
  model_name   varchar(128) NOT NULL,
  color        varchar(32),
  split        varchar(8)  NOT NULL CHECK (split IN ('TRAIN','VAL','TEST')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ml.dataset_version (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version         varchar(8)   NOT NULL UNIQUE,
  manifest_key    varchar(512) NOT NULL,
  builder_commit  varchar(40)  NOT NULL,
  counts          jsonb        NOT NULL,
  built_at        timestamptz  NOT NULL,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ml.training_run (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_version_id  bigint NOT NULL REFERENCES ml.dataset_version(id),
  base_weights        varchar(128) NOT NULL,
  metrics             jsonb        NOT NULL,
  model_key           varchar(512) NOT NULL,
  onnx_key            varchar(512) NOT NULL,
  created_at          timestamptz  NOT NULL DEFAULT now(),
  updated_at          timestamptz  NOT NULL DEFAULT now()
);
